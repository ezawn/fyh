-- Snowflake setup for Hax (SPEC 8.4).
-- Run once in Snowsight (Projects > Worksheets) as ACCOUNTADMIN. Safe to re-run.
-- Replace <PUBLIC_KEY> with the body of the server's public key (no BEGIN/END lines).

USE ROLE ACCOUNTADMIN;

-- Cortex: most Claude models are only reachable through cross-region inference.
ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

-- Compute: tiny warehouse that suspends after 60 s idle to save trial credits.
CREATE WAREHOUSE IF NOT EXISTS RETRO_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- Storage (SPEC 8.4)
CREATE DATABASE IF NOT EXISTS RETRO;
CREATE TABLE IF NOT EXISTS RETRO.PUBLIC.CARTRIDGES (
  ID STRING PRIMARY KEY, SCHEMA_VERSION INT, STATUS STRING,
  DATA VARIANT, CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS RETRO.PUBLIC.REMIX_LINES (
  CHARACTER_ID STRING, WORLD_ID STRING, DATA VARIANT,
  CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (CHARACTER_ID, WORLD_ID)
);

-- Role for the server: read/write the two tables and call Cortex, nothing else.
CREATE ROLE IF NOT EXISTS RETRO_APP;
GRANT USAGE ON WAREHOUSE RETRO_WH TO ROLE RETRO_APP;
GRANT USAGE ON DATABASE RETRO TO ROLE RETRO_APP;
GRANT USAGE ON SCHEMA RETRO.PUBLIC TO ROLE RETRO_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE RETRO.PUBLIC.CARTRIDGES TO ROLE RETRO_APP;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE RETRO.PUBLIC.REMIX_LINES TO ROLE RETRO_APP;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE RETRO_APP;

-- Service user for the server: key-pair login, so no password or MFA prompt.
CREATE USER IF NOT EXISTS RETRO_SERVER
  TYPE = SERVICE
  DEFAULT_ROLE = RETRO_APP
  DEFAULT_WAREHOUSE = RETRO_WH
  DEFAULT_NAMESPACE = RETRO.PUBLIC;
ALTER USER RETRO_SERVER SET RSA_PUBLIC_KEY = '<PUBLIC_KEY>';
GRANT ROLE RETRO_APP TO USER RETRO_SERVER;

-- Checks: the first should say ANY_REGION, the second should list claude-opus-5-5.
SHOW PARAMETERS LIKE 'CORTEX_ENABLED_CROSS_REGION' IN ACCOUNT;
SHOW CORTEX BASE MODELS IN SCHEMA SNOWFLAKE.MODELS;
-- Copy this value into SNOWFLAKE_ACCOUNT in .env:
SELECT CURRENT_ORGANIZATION_NAME() || '-' || CURRENT_ACCOUNT_NAME() AS SNOWFLAKE_ACCOUNT;
