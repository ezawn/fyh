// Builds scripts/snowflake/seed.sql from every valid cartridge in content/.
// Run: npx tsx scripts/snowflake/make-seed-sql.ts
// Then paste seed.sql into a Snowsight worksheet and run it (after setup.sql).
// No Snowflake driver needed, and safe to re-run (replaces cartridges by id).
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { validateCartridge } from "../../src/shared/validate";
import { Cartridge } from "../../src/shared/schema";

const files = (await readdir("content")).filter((f) => f.endsWith(".json"));
const statements: string[] = [
  "-- Generated by scripts/snowflake/make-seed-sql.ts. Do not edit by hand.",
  "USE ROLE RETRO_APP;",
  "USE WAREHOUSE RETRO_WH;",
  "USE SCHEMA RETRO.PUBLIC;",
  "",
];

let count = 0;
for (const f of files) {
  const json = JSON.parse(await readFile(path.join("content", f), "utf8"));
  const problems = validateCartridge(json);
  if (problems.length) {
    console.error(`✗ skipping ${f}: ${problems.length} problem(s), run npm run check:content`);
    continue;
  }
  const cart = Cartridge.parse(json);
  const body = JSON.stringify(cart);
  if (body.includes("$$")) throw new Error(`${f} contains "$$", which would break the SQL string`);
  const id = cart.id.replace(/'/g, "''");
  statements.push(
    `DELETE FROM CARTRIDGES WHERE ID = '${id}';`,
    `INSERT INTO CARTRIDGES (ID, SCHEMA_VERSION, STATUS, DATA, CREATED_AT)`,
    `  SELECT '${id}', ${cart.schemaVersion}, '${cart.status}', PARSE_JSON($$${body}$$), '${cart.createdAt}'::TIMESTAMP_TZ;`,
    "",
  );
  count++;
  console.log(`✓ ${cart.id}`);
}

statements.push("SELECT ID, STATUS, DATA:character:name::STRING AS CHARACTER, DATA:world:name::STRING AS WORLD FROM CARTRIDGES ORDER BY ID;");
const out = path.join("scripts", "snowflake", "seed.sql");
await writeFile(out, statements.join("\n") + "\n");
console.log(`Wrote ${out} with ${count} cartridge(s).`);
